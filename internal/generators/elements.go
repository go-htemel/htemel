func RenderFunc() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("RenderFunc").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).
		Parse(`
// Render writes the opening tag and its attributes, then {{ if .Void }}returns: <{{ .Tag }}> is a void element,
// so it is self closing and has no children.{{ else if .HasChildren }}renders each child, then writes the closing tag.{{ else }}writes the closing tag: <{{ .Tag }}> has no children.{{ end }}
//
// Output is written directly to w as many small writes, with no intermediate buffering.
// Pass a buffered writer, or use htemel.Render, when w is expensive to write to. If Render
// fails, part of the output may already be in w; to serve HTTP use htemel.Write or
// htemel.Handler, which write nothing when rendering fails.
func (e *{{ .Tag | goIdent }}Element) Render(w io.Writer) error {
	if e.attributes.Len() == 0 {
		if _, err := io.WriteString(w, "<{{ .Tag }}>"); err != nil {
			return err
		}
	} else {
		if _, err := io.WriteString(w, "<{{ .Tag }}"); err != nil {
			return err
		}
		if _, err := e.attributes.WriteTo(w); err != nil {
			return err
		}
		if _, err := io.WriteString(w, ">"); err != nil {
			return err
		}
	}
{{ if .Void }}
	return nil
{{- else }}
{{- if .HasChildren }}
	for _, child := range e.children {
		if err := child.Render(w); err != nil {
			return err
		}
	}
{{ end }}
	_, err := io.WriteString(w, "</{{ .Tag }}>")
	return err
{{- end }}
}
`))

	is := ImportSet{}

	return tmpl, is.Add("io").Add("github.com/go-htemel/htemel/internal/render")
}
