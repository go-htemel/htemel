func ClassFunc() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("ClassFunc").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).Parse(`
// Class adds classes to the element's class attribute. It is additive: each argument may hold
// several space-separated classes, which are appended in order after the classes already set;
// a class that is already present is not repeated. Use SetClass to replace the attribute.
func (e *{{ .Tag | goIdent }}Element) Class(classes ...string) *{{ .Tag | goIdent }}Element {
	current, _ := e.attributes.Get("class")
	if v := render.AppendClasses(current, classes); v != current {
		e.attributes.Set("class", v)
	}
	return e
}

// SetClass replaces the element's class attribute with the given classes, joined by spaces.
// Duplicate classes are removed; with no non-empty classes the attribute is removed.
func (e *{{ .Tag | goIdent }}Element) SetClass(classes ...string) *{{ .Tag | goIdent }}Element {
	if v := render.AppendClasses("", classes); v != "" {
		e.attributes.Set("class", v)
	} else {
		e.attributes.Remove("class")
	}
	return e
}

// AddClass appends classes to the element. It is the same as Class.
//
// Deprecated: Class is additive; use Class.
func (e *{{ .Tag | goIdent }}Element) AddClass(classes ...string) *{{ .Tag | goIdent }}Element {
	return e.Class(classes...)
}
`))

	is := ImportSet{}

	return tmpl, is.Add("github.com/go-htemel/htemel/internal/render")
}

func ToggleClassFunc() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("ToggleClassFunc").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).Parse(`
// ToggleClass toggles a class on or off.
func (e *{{ .Tag | goIdent }}Element) ToggleClass(class string, enable bool) *{{ .Tag | goIdent }}Element {
	current, ok := e.attributes.Get("class")
	classes := strings.Fields(current)
	idx := slices.Index(classes, class)
	if enable && idx == -1 {
		classes = append(classes, class)
	} else if !enable && idx >= 0 {
		classes = slices.Delete(classes, idx, idx+1)
	}
	if len(classes) == 0 {
		if ok {
			e.attributes.Remove("class")
		}
		return e
	}
	e.attributes.Set("class", strings.Join(classes, " "))
	return e
}
`))

	is := ImportSet{}

	return tmpl, is.Add("slices").Add("strings")
}

func AttrFunc() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("AttrFunc").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).Parse(`
// Attr sets an arbitrary attribute. The value is HTML-escaped; the name is written as-is and must
// be a valid attribute name. Useful for attributes not covered by the spec (e.g. htmx/Datastar).
// Setting an existing attribute updates its value but keeps its original position.
func (e *{{ .Tag | goIdent }}Element) Attr(name, value string) *{{ .Tag | goIdent }}Element {
	e.attributes.Set(name, value)
	return e
}

// AttrUnsafe sets an arbitrary attribute without escaping its value. Never pass untrusted input.
func (e *{{ .Tag | goIdent }}Element) AttrUnsafe(name, value string) *{{ .Tag | goIdent }}Element {
	e.attributes.SetUnsafe(name, value)
	return e
}

// BoolAttr sets an arbitrary boolean attribute: rendered bare when on is true, omitted when false.
func (e *{{ .Tag | goIdent }}Element) BoolAttr(name string, on bool) *{{ .Tag | goIdent }}Element {
	e.attributes.SetBool(name, on)
	return e
}
`))

	return tmpl, nil
}

