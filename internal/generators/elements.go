type ImportSet map[string]struct{}

func (is ImportSet) Add(i string) ImportSet {
	if _, ok := is[i]; !ok {
		is[i] = struct{}{}
	}
	return is
}

func (is ImportSet) Merge(other ImportSet) {
	for k := range other {
		is.Add(k)
	}
}

type TemplateFunc func() (*template.Template, ImportSet)

// goIdent converts a tag, attribute or enum value name into an exported Go identifier, preserving
// the name's own interior capitals. Every run of characters that is not a letter or digit (such as
// '-', ':' or '.') is a word break and is dropped, and the first letter of each word is upper-cased:
//
//	div             -> Div
//	clipPath        -> ClipPath
//	feGaussianBlur  -> FeGaussianBlur
//	accept-charset  -> AcceptCharset
//	stroke-width    -> StrokeWidth
//	xlink:href      -> XlinkHref
//
// A result that would start with a digit is prefixed with "V" so it stays a valid identifier.
func goIdent(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	out := b.String()
	if out == "" || unicode.IsDigit(rune(out[0])) {
		out = "V" + out
	}
	return out
}

func SourceHeader(w io.Writer, pkg string, e *ElementPlan, children ...TemplateFunc) error {
	var (
		colTmpls   []*template.Template
		colImports = make(ImportSet)
	)

	colImports.Add("github.com/go-htemel/htemel")

	for _, child := range children {
		t, imps := child()
		colTmpls = append(colTmpls, t)
		colImports.Merge(imps)
	}

	tmpl := template.Must(template.New("Header").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).
		Parse(`// Code generated by htemel. DO NOT EDIT.
package {{ .PackageName }}

import (
{{ range $key, $value := .Imports }}  "{{ $key }}"
{{ end -}}
)
`))

	if err := tmpl.Execute(w, struct {
		PackageName string
		Imports     ImportSet
		Element     *ElementPlan
	}{
		PackageName: pkg,
		Imports:     colImports,
		Element:     e,
	}); err != nil {
		return err
	}

	for _, t := range colTmpls {
		if err := t.Execute(w, e); err != nil {
			return err
		}
	}

	return nil
}

// SlotInterface declares the element's child interface, when its content model needs one.
func SlotInterface() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("SlotInterface").Parse(`
{{ with .Slot }}
{{ .Doc }}
type {{ .Iface }} interface {
	htemel.Node
	{{ .Method }}()
}
{{ end }}
`))

	return tmpl, nil
}

// SlotMethods implements the child interfaces of other elements that this element may appear in.
func SlotMethods() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("SlotMethods").Funcs(template.FuncMap{"goIdent": goIdent}).Parse(`
{{ $tag := .Tag }}
{{- range .SlotMethods }}
// {{ .Method }} marks <{{ $tag }}> as a permitted child{{ if .Owner }} of <{{ .Owner }}>{{ end }} ({{ .Iface }}).
func (*{{ $tag | goIdent }}Element) {{ .Method }}() {}
{{ end }}
`))

	return tmpl, nil
}

