// FileName is the output file for an element. It is lower-cased so that the generated package never
// depends on a case-sensitive file system for tags with interior capitals (clipPath, feGaussianBlur).
func FileName(e *spec.Element) string {
	return strings.ToLower(e.Tag) + ".go"
}

// Options configures GenerateWith.
type Options struct {
	// SlotsFile, when set, is the path of a Go file in package htemel that receives the
	// child-interface marker methods of htemel.Wildcard, htemel.NodeFunc, *htemel.TextElement and
	// the category markers, so that Group, Each, Text and friends are accepted by the
	// element-specific child interfaces of the generated package. It only makes sense when
	// generating the packages of github.com/go-htemel/htemel itself.
	SlotsFile string
}

// Generate writes one Go file per element of sp into dir, as package pkg. Global attributes are merged
// into every element first (an element's own attribute of the same name wins), and the resulting Go
// identifiers and file names are checked for collisions before anything is written.
func Generate(sp *spec.Spec, dir, pkg string) error {
	return GenerateWith(sp, dir, pkg, Options{})
}

// GenerateWith is Generate with options.
func GenerateWith(sp *spec.Spec, dir, pkg string, opts Options) error {
	mergeGlobals(sp)

	p, err := NewPlan(sp, pkg)
	if err != nil {
		return err
	}
	if err := p.Check(); err != nil {
		return err
	}

	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}

	for _, e := range p.Elements {
		if err := generateElement(dir, p, e); err != nil {
			return fmt.Errorf("<%s>: %w", e.Tag, err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, enumsFile), p.enumsSource(), 0o644); err != nil {
		return err
	}
	if p.Foreign {
		if err := os.WriteFile(filepath.Join(dir, contentFile), p.contentSource(), 0o644); err != nil {
			return err
		}
	}

	if err := fmtFiles(dir); err != nil {
		return err
	}

	if opts.SlotsFile != "" {
		src, err := imports.Process(opts.SlotsFile, p.slotsSource(), nil)
		if err != nil {
			return fmt.Errorf("%s: %w", opts.SlotsFile, err)
		}
		return os.WriteFile(opts.SlotsFile, src, 0o644)
	}
	return nil
}

func mergeGlobals(sp *spec.Spec) {
	for _, e := range sp.Elements {
		for _, a := range sp.Attributes {
			if !slices.ContainsFunc(e.Attributes, func(eAttr spec.Attribute) bool {
				return a.GetName() == eAttr.GetName()
			}) {
				e.Attributes = append(e.Attributes, a)
			}
		}
	}
}

func generateElement(dir string, p *Plan, e *ElementPlan) error {
	buf := &bytes.Buffer{}

	funcs := []TemplateFunc{
		SlotInterface,
		BaseStruct,
		BaseFunc,
		BaseCondFunc,
		BaseTernaryFunc,
		ChildrenFunc,
		WithFunc,
		TextFunc,
		TextfFunc,
		IfFunc,
		IfElseFunc,
		IfThenFunc,
		AddClassFunc,
		ToggleClassFunc,
		AttrFunc,
		AttrsFunc,
		SlotMethods,
		BuildAttributes(p, e),
		RenderFunc,
	}

	if err := SourceHeader(buf, p.Pkg, e, funcs...); err != nil {
		return err
	}

	return os.WriteFile(filepath.Join(dir, FileName(e.Element)), buf.Bytes(), 0o644)
}

func fmtFiles(dir string) error {
	opt := &imports.Options{
		AllErrors:  true,
		Comments:   true,
		TabIndent:  true,
		TabWidth:   8,
		FormatOnly: false,
	}

	return filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}

		if info.IsDir() || filepath.Ext(path) != ".go" {
			return nil
		}

		f, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		fixed, err := imports.Process(path, f, opt)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}

		return os.WriteFile(path, fixed, 0o644)
	})
}

// enumsSource is the package's enums.go: the shared enum types, plus a list of the enum
// attributes that kept per-element types.
func (p *Plan) enumsSource() []byte {
	b := &bytes.Buffer{}
	b.WriteString("// Code generated by htemel. DO NOT EDIT.\n\n")
	b.WriteString("// Enumerated attribute types shared by every element that has the attribute. An attribute\n")
	b.WriteString("// whose allowed values differ between elements has one type per element instead, named\n")
	b.WriteString("// <Element><Attribute>")
	if len(p.EnumReport) == 0 {
		b.WriteString(".\n")
	} else {
		b.WriteString(":\n//\n")
		for _, r := range p.EnumReport {
			b.WriteString("//   - " + r + "\n")
		}
	}
	b.WriteString("\npackage " + p.Pkg + "\n")

	for _, name := range slices.Sorted(maps.Keys(p.SharedEnums)) {
		s := p.SharedEnums[name]
		fmt.Fprintf(b, "\n// %s is a value of the %q attribute.\ntype %s string\n", s.Type, name, s.Type)
		b.WriteString(enumConsts(s.Type, s.Attr))
	}
	return b.Bytes()
}

// enumConsts declares the constants (and Custom constructor) of the enum type typ.
func enumConsts(typ string, a *spec.AttributeTypeEnum) string {
	b := &strings.Builder{}
	if len(a.Allowed) > 0 || a.AllowEmpty {
		b.WriteString("\nconst (\n")
		for _, v := range slices.Sorted(maps.Keys(a.Allowed)) {
			b.WriteString("\t" + typ + goIdent(v) + " " + typ + " = \"" + v + "\"\n")
		}
		if a.AllowEmpty {
			b.WriteString("\t" + typ + "Empty " + typ + " = \"\"\n")
		}
		b.WriteString(")\n")
	}
	if a.AllowCustom {
		b.WriteString("\n// " + typ + "Custom returns s as a " + typ + ", for values not listed in the specification.\n")
		b.WriteString("func " + typ + "Custom(s string) " + typ + " {\n\treturn " + typ + "(s)\n}\n")
	}
	return b.String()
}

// contentSource declares the package-wide child interface of a foreign package (svg.Content).
func (p *Plan) contentSource() []byte {
	b := &bytes.Buffer{}
	b.WriteString("// Code generated by htemel. DO NOT EDIT.\n\npackage " + p.Pkg + "\n\nimport \"github.com/go-htemel/htemel\"\n")
	for _, s := range p.Slots {
		if s.Owner != "" {
			continue
		}
		fmt.Fprintf(b, `
// %[1]s is the child type of every element in this package. It is implemented by every element
// of the package, by text (htemel.Text, htemel.TextUnsafe) and by the unchecked nodes of package
// htemel (Group, Each, If, Unchecked, ...). The model is closed but loose: any element of the
// package may contain any other.
type %[1]s interface {
	htemel.Node
	%[2]s()
}
`, s.Iface, s.Method)
	}
	return b.Bytes()
}

// slotsSource is the file in package htemel that adds every child-interface method of this
// package to the wildcard types, to text, and to the category markers that carry it.
func (p *Plan) slotsSource() []byte {
	b := &bytes.Buffer{}
	fmt.Fprintf(b, "// Code generated by htemel. DO NOT EDIT.\n\npackage htemel\n\n")
	fmt.Fprintf(b, "// Marker methods of the child interfaces of package %s. They have no behaviour: they let\n", p.Pkg)
	fmt.Fprintf(b, "// Wildcard and NodeFunc (and Text, and the category markers, where the content model permits\n// them) satisfy those interfaces.\n")
	for _, s := range p.Slots {
		fmt.Fprintf(b, "\n// %s.%s\n", p.Pkg, s.Iface)
		recv := []string{"Wildcard", "NodeFunc"}
		if s.Text {
			recv = append(recv, "*TextElement")
		}
		recv = append(recv, s.Carriers()...)
		for _, r := range recv {
			fmt.Fprintf(b, "func (%s) %s() {}\n", r, s.Method)
		}
	}
	return b.Bytes()
}

// elementMethods are the methods every generated element has regardless of its attributes; an
// attribute whose setter name equals one of these would not compile.
var elementMethods = []string{"With", "AddClass", "ToggleClass", "Attr", "AttrUnsafe", "BoolAttr", "Attrs", "SetAttr", "SetAttrUnsafe", "Render", "IfThen"}

// childrenMethods are the extra methods of elements that take children; textMethods those of
// elements that permit text.
var (
	childrenMethods = []string{"Children", "If", "IfElse"}
	textMethods     = []string{"Text", "Textf"}
)

// CheckNames reports every Go identifier or output file name that the given elements (with globals
// already merged) would generate more than once, e.g. two tags differing only in case, two attributes
// that mangle to the same setter (stroke-width and strokeWidth), an attribute setter clashing with a
// built-in method, or an enum type clashing with another element's constructor.
func CheckNames(elements []*spec.Element) error {
	p, err := NewPlan(&spec.Spec{Name: "check", Elements: elements}, "check")
	if err != nil {
		return err
	}
	return p.Check()
}

// Check reports every Go identifier or output file name the plan would generate more than once:
// package-level names (constructors, element types, child interfaces, enum types and constants)
// and, per element, method and embedded field names.
func (p *Plan) Check() error {
	var problems []string

	pkgNames := map[string]string{} // identifier -> what declared it
	files := map[string]string{enumsFile: "the shared enum file"}
	if p.Foreign {
		files[contentFile] = "the content interface file"
	}

	declare := func(name, what string) {
		if prev, ok := pkgNames[name]; ok {
			problems = append(problems, fmt.Sprintf("package-level %s is declared by both %s and %s", name, prev, what))
			return
		}
		pkgNames[name] = what
	}

	for _, s := range p.Slots {
		declare(s.Iface, "child interface "+s.Iface)
	}
	for _, name := range slices.Sorted(maps.Keys(p.SharedEnums)) {
		s := p.SharedEnums[name]
		for _, n := range enumNames(s.Type, s.Attr) {
			declare(n, fmt.Sprintf("shared enum attribute %q", name))
		}
	}

	for _, e := range p.Elements {
		tag := goIdent(e.Tag)
		where := "<" + e.Tag + ">"

		if prev, ok := files[FileName(e.Element)]; ok {
			problems = append(problems, fmt.Sprintf("file %s is produced by both %s and %s", FileName(e.Element), prev, where))
		} else {
			files[FileName(e.Element)] = where
		}

		declare(tag, where)
		declare(tag+"If", where)
		declare(tag+"Element", where)
		if e.HasChildren {
			declare(tag+"Ternary", where)
		}

		methods := map[string]string{}
		method := func(name, what string) {
			if prev, ok := methods[name]; ok {
				problems = append(problems, fmt.Sprintf("%s: method %s is declared by both %s and %s", where, name, prev, what))
				return
			}
			methods[name] = what
		}
		for _, m := range elementMethods {
			method(m, "the built-in "+m)
		}
		if e.HasChildren {
			for _, m := range childrenMethods {
				method(m, "the built-in "+m)
			}
		}
		if e.Text {
			for _, m := range textMethods {
				method(m, "the built-in "+m)
			}
		}
		for _, m := range e.Markers {
			field := strings.TrimPrefix(m, "htemel.")
			method(field, "the embedded marker "+field)
		}
		for _, s := range e.memberOf {
			method(s.Method, "the "+s.Iface+" marker method")
		}

		for _, attr := range e.Attributes {
			name := attr.GetName()
			what := fmt.Sprintf("attribute %q", name)
			method(goIdent(name), what)

			switch a := attr.(type) {
			case *spec.AttributeTypePrefixedCustom:
				method(goIdent(name)+"Unsafe", what)
			case *spec.AttributeTypeEnum:
				if _, shared := p.SharedEnums[name]; shared {
					continue
				}
				ewhere := where + " " + what
				for _, n := range enumNames(p.EnumType(e.Tag, name), a) {
					declare(n, ewhere)
				}
			}
		}
	}

	if len(problems) > 0 {
		slices.Sort(problems)
		return fmt.Errorf("generated names collide:\n  %s", strings.Join(problems, "\n  "))
	}

	return nil
}
