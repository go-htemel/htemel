// HTMLDirectGlobals are the global attributes of the html package that stay direct setter methods
// on every element (ADR 0010). Every other global attribute moves into the generated Globals
// struct, applied with the Globals method. class is handled by the built-in Class, SetClass and
// ToggleClass methods.
var HTMLDirectGlobals = []string{
	"id", "class", "style", "title", "lang", "dir", "hidden", "tabindex", "role",
	"autofocus", "draggable", "popover", "nonce", "data", "aria",
}

// globalsFile is the generated file declaring the Globals struct.
const globalsFile = "globals.go"

// moveGlobals takes every global attribute of globals that is not named in direct out of the
// elements' attribute lists and into p.Globals, in spec order. Only the global attribute itself
// moves: an element that declares its own attribute of the same name keeps its setter. Every
// element gets the Globals method.
func (p *Plan) moveGlobals(globals []spec.Attribute, direct []string) error {
	var moved []spec.Attribute
	for _, g := range globals {
		if slices.Contains(direct, g.GetName()) {
			continue
		}
		switch a := g.(type) {
		case *spec.AttributeTypePrefixedCustom:
			return fmt.Errorf("global attribute %q is a prefixed family and must stay a direct method", a.Name)
		case *spec.AttributeTypeEnum:
			if _, ok := p.SharedEnums[a.Name]; !ok {
				return fmt.Errorf("global enum attribute %q has no shared type and cannot move into Globals", a.Name)
			}
		}
		moved = append(moved, g)
	}
	if len(moved) == 0 {
		return nil
	}
	p.Globals = moved
	for _, ep := range p.Elements {
		ep.HasGlobals = true
		ep.Attributes = slices.DeleteFunc(slices.Clone(ep.Attributes), func(a spec.Attribute) bool {
			return slices.Contains(moved, a) // identity: the merged global, not an own attribute
		})
	}
	return nil
}

// GlobalsFunc generates the Globals method of an element, when the package has a Globals struct.
func GlobalsFunc() (*template.Template, ImportSet) {
	tmpl := template.Must(template.New("GlobalsFunc").
		Funcs(template.FuncMap{
			"goIdent": goIdent,
		}).Parse(`
{{ if .HasGlobals }}
// Globals sets the less common global attributes held in g (see Globals). Zero fields are
// skipped; the others are set in the order Globals declares them.
func (e *{{ .Tag | goIdent }}Element) Globals(g Globals) *{{ .Tag | goIdent }}Element {
	g.apply(&e.attributes)
	return e
}
{{ end }}
`))

	return tmpl, nil
}

// globalsSource is the package's globals.go: the Globals struct and its apply method.
func (p *Plan) globalsSource() []byte {
	b := &bytes.Buffer{}
	b.WriteString("// Code generated by htemel. DO NOT EDIT.\n\npackage " + p.Pkg + "\n\n")
	b.WriteString("import (\n\t\"strconv\"\n\t\"strings\"\n\n\t\"github.com/go-htemel/htemel/internal/render\"\n)\n\n")
	b.WriteString(`// Globals holds the global attributes that are not direct methods on every element, so that
// the method set of an element stays readable. Apply them with the Globals method of any element:
//
//	Div().Globals(Globals{Itemscope: true, Itemtype: []string{"https://schema.org/Person"}})
//
// The zero value of a field means "not set": it is skipped, not rendered empty. Bool fields render
// the bare attribute when true. Fields are applied in declaration order, so output is
// deterministic. To render an enumerated attribute with an empty value, or to remove an attribute,
// use Attr, BoolAttr or the element's own methods.
type Globals struct {
`)
	for _, a := range p.Globals {
		name := a.GetName()
		doc := fmt.Sprintf("%s is the %q attribute.", goIdent(name), name)
		if d := attrDescription(a); d != "" {
			doc += " " + d
		}
		for _, line := range wrap(doc, 96) {
			b.WriteString("\t// " + line + "\n")
		}
		if u, ok := a.(*spec.AttributeTypeString); ok && u.URL {
			b.WriteString("\t// Value is a URL; validate untrusted input with htemel.URL.\n")
		}
		if a.IsDeprecated() {
			fmt.Fprintf(b, "\t//\n\t// Deprecated: the %q attribute is deprecated or obsolete in its source specification.\n", name)
		}
		fmt.Fprintf(b, "\t%s %s\n", goIdent(name), p.globalFieldType(a))
	}
	b.WriteString("}\n\n// apply sets every non-zero field of g on a, in declaration order.\nfunc (g Globals) apply(a *render.Attrs) {\n")
	for _, attr := range p.Globals {
		name, field := attr.GetName(), "g."+goIdent(attr.GetName())
		switch attr.(type) {
		case *spec.AttributeTypeString, *spec.AttributeTypeChar:
			fmt.Fprintf(b, "\tif %s != \"\" {\n\t\ta.Set(%q, %s)\n\t}\n", field, name, field)
		case *spec.AttributeTypeEnum:
			fmt.Fprintf(b, "\tif %s != \"\" {\n\t\ta.Set(%q, string(%s))\n\t}\n", field, name, field)
		case *spec.AttributeTypeNumber:
			fmt.Fprintf(b, "\tif %s != 0 {\n\t\ta.Set(%q, strconv.Itoa(%s))\n\t}\n", field, name, field)
		case *spec.AttributeTypeFloat:
			fmt.Fprintf(b, "\tif %s != 0 {\n\t\ta.Set(%q, strconv.FormatFloat(%s, 'g', -1, 64))\n\t}\n", field, name, field)
		case *spec.AttributeTypeBool:
			fmt.Fprintf(b, "\tif %s {\n\t\ta.SetBool(%q, true)\n\t}\n", field, name)
		case *spec.AttributeTypeSST:
			fmt.Fprintf(b, "\tif len(%s) > 0 {\n\t\ta.Set(%q, strings.Join(%s, \" \"))\n\t}\n", field, name, field)
		}
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// globalFieldType is the Go type of the Globals field for a.
func (p *Plan) globalFieldType(a spec.Attribute) string {
	switch a := a.(type) {
	case *spec.AttributeTypeEnum:
		return p.SharedEnums[a.Name].Type
	case *spec.AttributeTypeNumber:
		return "int"
	case *spec.AttributeTypeFloat:
		return "float64"
	case *spec.AttributeTypeBool:
		return "bool"
	case *spec.AttributeTypeSST:
		return "[]string"
	default: // string, char (a one-rune string)
		return "string"
	}
}

// attrDescription is the spec description of a, on one line.
func attrDescription(a spec.Attribute) string {
	var d string
	switch a := a.(type) {
	case *spec.AttributeTypeString:
		d = a.Description
	case *spec.AttributeTypeChar:
		d = a.Description
	case *spec.AttributeTypeNumber:
		d = a.Description
	case *spec.AttributeTypeFloat:
		d = a.Description
	case *spec.AttributeTypeBool:
		d = a.Description
	case *spec.AttributeTypeEnum:
		d = a.Description
	case *spec.AttributeTypeSST:
		d = a.Description
	case *spec.AttributeTypePrefixedCustom:
		d = a.Description
	}
	return strings.Join(strings.Fields(d), " ")
}

// wrap splits s into lines of at most width bytes, breaking at spaces.
func wrap(s string, width int) []string {
	var lines []string
	line := ""
	for _, w := range strings.Fields(s) {
		if line != "" && len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = ""
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}
